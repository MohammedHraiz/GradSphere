ALTER TABLE tasks
    ADD COLUMN IF NOT EXISTS priority VARCHAR(32) NOT NULL DEFAULT 'MEDIUM';

UPDATE tasks
SET status = CASE status
    WHEN 'TODO' THEN 'NOT_STARTED'
    WHEN 'DONE' THEN 'COMPLETED'
    WHEN 'OVERDUE' THEN 'IN_PROGRESS'
    ELSE status
END;

ALTER TABLE milestones
    ADD COLUMN IF NOT EXISTS status VARCHAR(32) NOT NULL DEFAULT 'NOT_STARTED',
    ADD COLUMN IF NOT EXISTS key_requirements TEXT,
    ADD COLUMN IF NOT EXISTS review_feedback TEXT,
    ADD COLUMN IF NOT EXISTS submission_file_path VARCHAR(500),
    ADD COLUMN IF NOT EXISTS submission_file_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS submission_notes TEXT,
    ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMP WITH TIME ZONE;
